package us.neotechnica.panther.designsystem.modules.alertkit.constants

// MARK: - Float

/** The layout and timing values of the alert text field view. */
object AlertTextFieldViewFloats {
    /** The bottom padding of the alert. */
    const val ALERT_BOTTOM_PADDING = 12f

    /** The horizontal padding of the alert. */
    const val ALERT_HORIZONTAL_PADDING = 15f

    /** The width of the border, in pixels. */
    const val BORDER_WIDTH_PIXELS = 1f

    /** The width of the clear button area. */
    const val CLEAR_BUTTON_AREA_WIDTH = 30.33f

    /** The diameter of the clear button. */
    const val CLEAR_BUTTON_DIAMETER = 13f

    /** Half the length of the clear button's glyph strokes. */
    const val CLEAR_BUTTON_GLYPH_HALF_LENGTH = 2.1f

    /** The stroke width of the clear button's glyph. */
    const val CLEAR_BUTTON_GLYPH_STROKE_WIDTH = 1.2f

    /** The trailing padding of the clear button. */
    const val CLEAR_BUTTON_TRAILING_PADDING = 13.33f

    /** The corner radius. */
    const val CORNER_RADIUS = 6f

    /** The height of the field. */
    const val HEIGHT = 30.67f

    /** The font size of the text. */
    const val TEXT_FONT_SIZE = 13f

    /** The horizontal padding of the text. */
    const val TEXT_HORIZONTAL_PADDING = 7f

    /** The vertical offset of the text. */
    const val TEXT_VERTICAL_OFFSET = 0.6f
}
