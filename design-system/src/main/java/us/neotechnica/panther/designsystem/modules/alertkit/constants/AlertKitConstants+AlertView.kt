// MARK: - Float

/** The layout and timing values of the alert view. */
object AlertViewFloats {
    /** The height of the action button. */
    const val ACTION_BUTTON_HEIGHT = 44f

    /** The font size of the action label. */
    const val ACTION_LABEL_FONT_SIZE = 17f

    /** The horizontal padding of the content. */
    const val CONTENT_HORIZONTAL_PADDING = 16f

    /** The distance from the content's last baseline to the alert's bottom. */
    const val CONTENT_LAST_BASELINE_TO_BOTTOM = 23.67f

    /** The distance from the content's top to its first baseline. */
    const val CONTENT_TOP_TO_FIRST_BASELINE = 36.33f

    /** The corner radius. */
    const val CORNER_RADIUS = 13f

    /** The maximum width of an action label in a horizontal button row. */
    const val HORIZONTAL_ACTION_LABEL_MAXIMUM_WIDTH = 103f

    /** The font size of the message label. */
    const val MESSAGE_LABEL_FONT_SIZE = 13f

    /** The line height of the message label. */
    const val MESSAGE_LABEL_LINE_HEIGHT = 16f

    /** The distance from the message's top to its first baseline. */
    const val MESSAGE_TOP_TO_FIRST_BASELINE = 15f

    /** The scale at which the alert begins presenting. */
    const val PRESENTATION_INITIAL_SCALE = 1.2f

    /** The font size of the title label. */
    const val TITLE_LABEL_FONT_SIZE = 17f

    /** The line height of the title label. */
    const val TITLE_LABEL_LINE_HEIGHT = 22f

    /** The distance from the title's last baseline to the message. */
    const val TITLE_LAST_BASELINE_TO_BOTTOM = 5f

    /** The width of the alert. */
    const val WIDTH = 270f
}
