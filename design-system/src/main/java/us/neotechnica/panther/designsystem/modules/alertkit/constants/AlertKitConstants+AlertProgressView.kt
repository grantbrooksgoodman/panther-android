    const val PROGRESS_ANIMATION_DURATION = 0.25f

    /** The height reserved for the bar. */
    const val RESERVED_HEIGHT = 32f

    /** The height reserved for the bar when a cancel action is present. */
    const val RESERVED_HEIGHT_WITH_CANCEL_ACTION = 16f
}
